"""Self-contained HTML audit report (no external assets)."""
import html, json
import numpy as np
import pandas as pd

COLORS = {"audited": "#2a78d6", "unsupported": "#d9d8d2", "reversed": "#eb6834", "neighbour": "#7a5fc2", "offtarget": "#c2410c",
          "guide_specific": "#0f766e", "unstable": "#a16207", "untestable_parent_not_perturbed": "#f1f0ec",
          "untestable_child_not_measured": "#f1f0ec", "untestable_ineffective_knockdown": "#e8e6df"}
ORDER = ["audited", "unsupported", "reversed", "neighbour", "offtarget", "guide_specific", "unstable",
         "untestable_ineffective_knockdown", "untestable_parent_not_perturbed", "untestable_child_not_measured"]


def _bar_svg(summary, width=640, row_h=26):
    rows = summary.to_dict("records")
    h = row_h * len(rows) + 30
    out = [f'<svg viewBox="0 0 {width} {h}" width="100%" role="img" aria-label="Verdicts by graph size">']
    x0, w = 90, width - 110
    for i, r in enumerate(rows):
        y = 10 + i * row_h; tot = max(sum(r.get(v, 0) for v in ORDER), 1); x = x0
        out.append(f'<text x="{x0 - 8}" y="{y + 15}" text-anchor="end" font-size="12" fill="#2b2b2a">top {r["top_k"]}</text>')
        for v in ORDER:
            n = r.get(v, 0)
            if not n: continue
            ww = w * n / tot
            out.append(f'<rect x="{x:.1f}" y="{y}" width="{max(ww - 1, 0.5):.1f}" height="{row_h - 8}" rx="2" fill="{COLORS[v]}"><title>{v}: {n}</title></rect>')
            x += ww
    out.append("</svg>")
    return "".join(out)


def html_report(edges, summary, title="perturbaudit report", params=None, max_rows=500):
    E = edges.head(max_rows).copy()
    show = [c for c in ["rank", "parent", "child", "score", "verdict", "z_parent_kd_on_child", "q_parent_kd_on_child",
                        "z_child_kd_on_parent", "parent_knockdown_z", "tss_distance", "guide_z", "stability"] if c in E]
    E = E[show]
    for c in E.select_dtypes("number").columns:
        E[c] = E[c].map(lambda v: "–" if (pd.isna(v) or (isinstance(v, float) and not np.isfinite(v))) else (f"{v:.3g}" if isinstance(v, float) else v))
    E = E.fillna("–").replace({"nan": "–", "": "–"})
    legend = "".join(f'<span class="k"><i style="background:{COLORS[v]}"></i>{v.replace("_", " ")}</span>' for v in ORDER[:7])
    head = "".join(f"<th>{html.escape(c)}</th>" for c in show)
    body = "".join("<tr>" + "".join(f"<td class='{html.escape(str(r['verdict']))}'>" + html.escape(str(r[c])) + "</td>" if c == "verdict" else f"<td>{html.escape(str(r[c]))}</td>" for c in show) + "</tr>" for _, r in E.iterrows())
    stbl = summary.to_html(index=False, border=0, classes="s")
    p = html.escape(json.dumps(params or {}, indent=1, default=str))
    tested = summary.iloc[-1] if len(summary) else {}
    return f"""<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{html.escape(title)}</title><style>
body{{font-family:system-ui,-apple-system,Segoe UI,sans-serif;color:#2b2b2a;max-width:1100px;margin:32px auto;padding:0 16px;line-height:1.45}}
h1{{font-size:22px;margin:0 0 4px}} h2{{font-size:16px;margin:28px 0 8px}} .muted{{color:#77766f}}
.k{{display:inline-flex;align-items:center;margin-right:14px;font-size:12px}} .k i{{width:12px;height:12px;border-radius:2px;margin-right:5px;display:inline-block}}
table{{border-collapse:collapse;font-size:12px;width:100%}} th,td{{padding:4px 6px;border-bottom:1px solid #e6e5df;text-align:left;white-space:nowrap}}
th{{position:sticky;top:0;background:#fafaf8}} .tw{{max-height:520px;overflow:auto;border:1px solid #e6e5df;border-radius:6px}}
td.audited{{color:#1d5fae;font-weight:600}} td.reversed{{color:#c2501f;font-weight:600}} td.unsupported{{color:#77766f}}
pre{{background:#fafaf8;padding:10px;border-radius:6px;font-size:11px;overflow:auto}}
@media (prefers-color-scheme: dark){{body{{background:#1b1b1a;color:#e9e8e3}} th{{background:#232322}} pre{{background:#232322}} th,td{{border-color:#333}}}}
</style></head><body>
<h1>{html.escape(title)}</h1><div class="muted">Edge verdicts from the screen's own controls. Verdict = first failing check: untestable, reversed, unsupported, off-target, neighbour, guide-specific, unstable; otherwise audited.</div>
<h2>Verdicts by graph size</h2><div>{legend}</div>{_bar_svg(summary)}
<h2>Summary table</h2><div class="tw">{stbl}</div>
<h2>Edges (top {len(E)})</h2><div class="tw"><table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table></div>
<h2>Parameters</h2><pre>{p}</pre>
<p class="muted">Generated by perturbaudit. "Unsupported" means the screen's knockdown of the parent did not move the child (|z| &lt; threshold and q above threshold); weak true effects below the screen's power also land here.</p>
</body></html>"""
